// Builds the MCP App view into ONE self-contained HTML file: dist/view.html
// (+ dist/view-html.mjs that exports the same string, for servers that embed it).
// Size tricks: minify, and replace zod's 40+ locale bundles with English only
// (zod is pulled in by ext-apps' App/Protocol for message validation; the view never shows zod errors).
import { build } from 'esbuild';
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { gzipSync } from 'node:zlib';

const here = dirname(fileURLToPath(import.meta.url));
const pkg = resolve(here, '..');

const zodEnglishOnly = {
  name: 'zod-english-only',
  setup(b) {
    b.onResolve({ filter: /locales\/index\.js$/ }, (args) =>
      args.importer.includes(`${'zod'}`) ? { path: 'zod-locales-en', namespace: 'zod-en', pluginData: dirname(args.importer) } : undefined,
    );
    b.onLoad({ filter: /.*/, namespace: 'zod-en' }, (args) => ({
      contents: `export { default as en } from ${JSON.stringify(resolve(args.pluginData, '../locales/en.js'))};`,
      resolveDir: args.pluginData,
    }));
  },
};

const js = await build({
  entryPoints: [resolve(pkg, 'src/main.ts')],
  bundle: true, format: 'esm', platform: 'browser', target: 'es2022',
  minify: true, legalComments: 'none', write: false, metafile: true,
  plugins: [zodEnglishOnly],
  define: { 'process.env.NODE_ENV': '"production"' },
});
const css = await build({ entryPoints: [resolve(pkg, 'src/styles.css')], bundle: true, minify: true, write: false, loader: { '.css': 'css' } });

const jsText = js.outputFiles[0].text.replace(/<\/script/gi, '<\\/script');
const cssText = css.outputFiles[0].text.replace(/<\/style/gi, '<\\/style');
const html = readFileSync(resolve(pkg, 'src/view.html'), 'utf8')
  .replace('/*__CSS__*/', () => cssText)
  .replace('/*__JS__*/', () => jsText);

mkdirSync(resolve(pkg, 'dist'), { recursive: true });
writeFileSync(resolve(pkg, 'dist/view.html'), html);
writeFileSync(resolve(pkg, 'dist/view-html.mjs'), `// generated by packages/view/scripts/build.mjs\nexport const VIEW_HTML = ${JSON.stringify(html)};\nexport default VIEW_HTML;\n`);
writeFileSync(resolve(pkg, 'dist/meta.json'), JSON.stringify(js.metafile));
const kb = (n) => (n / 1024).toFixed(1);
console.log(`[view] dist/view.html ${kb(Buffer.byteLength(html))} KB (gzip ${kb(gzipSync(html).length)} KB), js ${kb(jsText.length)} KB, css ${kb(cssText.length)} KB`);
